export function getContractTemplate() {
  return (db.prepare(`SELECT value FROM settings WHERE key='contract_template'`).get() || {}).value || DEFAULT_TEMPLATE;
}

// 渲染合同：代入租客/房源/合同信息
export function renderContract(ctx = {}) {
  const tpl = getContractTemplate();
  const siteName = (db.prepare(`SELECT value FROM settings WHERE key='site_name'`).get() || {}).value || 'LookHome';
  const sitePhone = (db.prepare(`SELECT value FROM settings WHERE key='site_phone'`).get() || {}).value || '';
  const pay = PAY_MODES[ctx.pay_mode] || PAY_MODES.monthly;
  const term = Number(ctx.term_months) > 0 ? Number(ctx.term_months) : 1;
  const rent = Number(ctx.monthly_rent) > 0 ? Number(ctx.monthly_rent) : 0;
  const firstPayment = rent > 0 ? rent * pay.months : '';
  const map = {
    site_name: siteName, site_phone: sitePhone,
    property_name: ctx.property_name || '', property_address: ctx.property_address || '',
    room_no: ctx.room_no || '', layout: ctx.layout || '', area: ctx.area || '',
    tenant_name: ctx.tenant_name || '', id_card: ctx.id_card || '', tenant_phone: ctx.tenant_phone || '',
    monthly_rent: ctx.monthly_rent || '', deposit: ctx.deposit || '',
    term_months: term, pay_mode_text: ctx.pay_mode_text || pay.text,
    first_payment: ctx.first_payment || firstPayment,
    start_date: ctx.start_date || '', end_date: ctx.end_date || '',
    sign_date: new Date().toLocaleDateString('zh-CN'),
  };
  return tpl.replace(/\{(\w+)\}/g, (m, k) => (k in map ? map[k] : m));
}
